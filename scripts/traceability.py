#!/usr/bin/env python3
"""Writes the FRD traceability matrix: every requirement ID of FRD.md with the tests that name
it and the release checklist's manual checks (specs/008-release-1-0/research.md R15).

Tests name FRD IDs in their Swift Testing display names (`@Test("US1 FR-MOVE-03: …")`) or, for
XCTest methods, in the `///` comment above `func test…`. Standard library only.

Usage:
  python3 scripts/traceability.py           # write specs/008-release-1-0/traceability.md
  python3 scripts/traceability.py --check   # fail if an ID is missing or the file is out of date
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SLICE = REPO / "specs" / "008-release-1-0"
ID = re.compile(r"\bFR-[A-Z]+-\d+\b")
DEFINITION = re.compile(r"^- \*\*(FR-[A-Z]+-\d+)\*\*(.*)$")
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')
FUNC = re.compile(r"\bfunc\s+(\w+)\s*\(")


def requirements(frd):
    """The FRD's IDs in their order, each with whether it was removed."""
    found = []
    for line in frd.read_text().splitlines():
        match = DEFINITION.match(line)
        if match:
            found.append((match.group(1), match.group(2).lstrip().startswith("*Removed")))
    return found


def tests(directories, root):
    """(file, test name, IDs) for every test in the Swift files under the directories."""
    found = []
    for directory in directories:
        for path in sorted(directory.rglob("*.swift")):
            relative = path.relative_to(root).as_posix()
            comment, attribute = [], None
            for line in path.read_text().splitlines():
                stripped = line.strip()
                if stripped.startswith("///"):
                    comment.append(stripped)
                    continue
                if stripped.startswith("@Test"):
                    attribute = [stripped]
                    continue
                if attribute is not None and not FUNC.search(stripped):
                    attribute.append(stripped)
                    continue
                function = FUNC.search(stripped)
                if function and (attribute is not None or function.group(1).startswith("test")):
                    text = " ".join(attribute or [])
                    display = STRING.search(text)
                    name = display.group(1) if display else function.group(1)
                    ids = ID.findall(text if attribute is not None else " ".join(comment))
                    if ids:
                        found.append((relative, name, sorted(set(ids))))
                if not stripped.startswith("@"):
                    comment, attribute = [], None
    return found


def manual_checks(checklist):
    """{FRD ID: ["RC-01 (passed, build 3)", …]} from the checklist's table rows."""
    checks = {}
    if not checklist.exists():
        return checks
    for line in checklist.read_text().splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 5 or not re.fullmatch(r"RC-\d+", cells[0]):
            continue
        build, result = cells[3], cells[4]
        state = f"{result}, build {build}" if result and build else (result or "open")
        for requirement in sorted(set(ID.findall(line))):
            checks.setdefault(requirement, []).append(f"{cells[0]} ({state})")
    return checks


def matrix(frd, directories, checklist, root):
    """The Markdown text and the IDs with neither a test nor a manual check."""
    named = tests(directories, root)
    checks = manual_checks(checklist)
    rows, counts, missing = [], {"covered": 0, "removed": 0, "missing": 0}, []
    for requirement, removed in requirements(frd):
        covering = [f"`{file}` › {name}".replace("|", "\\|")
                    for file, name, ids in named if requirement in ids]
        manual = checks.get(requirement, [])
        status = "removed" if removed else ("covered" if covering or manual else "missing")
        counts[status] += 1
        if status == "missing":
            missing.append(requirement)
        rows.append(f"| {requirement} | {status} | {'<br>'.join(covering) or '—'} | "
                    f"{'<br>'.join(manual) or '—'} |")

    def shown(path):
        return f"`{path.relative_to(root).as_posix() if path.is_relative_to(root) else path.name}`"

    lines = [
        "# FRD traceability",
        "",
        f"Generated by `scripts/traceability.py` from {shown(frd)}, the tests in "
        f"{', '.join(shown(d) for d in directories)} and {shown(checklist)}. Do",
        "not edit it by hand: after adding or renaming a test that names an FRD ID, run",
        "`python3 scripts/traceability.py` and commit this file with the test.",
        "",
        f"**Covered:** {counts['covered']} · **Removed:** {counts['removed']} · "
        f"**Missing:** {counts['missing']}",
        "",
        "| FRD ID | Status | Tests | Manual checks |",
        "|---|---|---|---|",
        *rows,
    ]
    return "\n".join(lines) + "\n", missing


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=REPO)
    parser.add_argument("--frd", type=Path, default=REPO / "FRD.md")
    parser.add_argument("--tests", type=Path, nargs="+", default=[
        REPO / "checkers" / "checkersTests",
        REPO / "checkers" / "checkersUITests",
        REPO / "checkers" / "CheckersEngine" / "Tests",
    ])
    parser.add_argument("--checklist", type=Path, default=SLICE / "checklists" / "release.md")
    parser.add_argument("--out", type=Path, default=SLICE / "traceability.md")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()

    root = arguments.root.resolve()
    text, missing = matrix(arguments.frd.resolve(), [d.resolve() for d in arguments.tests],
                           arguments.checklist.resolve(), root)
    if not arguments.check:
        arguments.out.write_text(text)
        print(f"Wrote {arguments.out}: {len(missing)} missing")
        return 0
    problems = []
    if missing:
        problems.append("No test or manual check names " + ", ".join(missing) + ".")
    if not arguments.out.exists() or arguments.out.read_text() != text:
        problems.append(f"{arguments.out} is out of date: run python3 scripts/traceability.py.")
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
